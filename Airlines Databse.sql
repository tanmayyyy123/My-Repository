-- Q1: Provide a SQL query that calculates the number of flights for each period of the day
-- morning, afternoon, evening, and night with the time slots defined as follows...
SELECT
    departure_airport,
    COUNT(CASE WHEN CAST(scheduled_departure AS TIME) < '12:00:00' THEN 1 END) AS morning_count,
    COUNT(CASE WHEN CAST(scheduled_departure AS TIME) >= '12:00:00' AND CAST(scheduled_departure AS TIME) < '16:00:00' THEN 1 END) AS afternoon_count,
    COUNT(CASE WHEN CAST(scheduled_departure AS TIME) >= '16:00:00' AND CAST(scheduled_departure AS TIME) < '20:00:00' THEN 1 END) AS evening_count,
    COUNT(CASE WHEN CAST(scheduled_departure AS TIME) >= '20:00:00' THEN 1 END) AS night_count
FROM
    flights
GROUP BY
    departure_airport
ORDER BY
    departure_airport ASC;


-- Q2: The airline wants to calculate the contribution of monthly revenue generated by
-- bookings to the overall revenue of the year...
WITH monthly_revenue AS (
    SELECT
        EXTRACT(YEAR FROM book_date) AS year,
        EXTRACT(MONTH FROM book_date) AS month,
        SUM(total_amount) AS mon_revenue
    FROM
        bookings
    GROUP BY
        EXTRACT(YEAR FROM book_date),
        EXTRACT(MONTH FROM book_date)
)
SELECT
    year,
    month,
    ROUND(mon_revenue / SUM(mon_revenue) OVER (PARTITION BY year), 2) AS revenue_contribution
FROM
    monthly_revenue
ORDER BY
    year ASC,
    month ASC;


-- Q3: Find out all the booking references where travellers took 'Airbus' flights...
SELECT DISTINCT b.book_ref
FROM bookings b
JOIN tickets t ON b.book_ref = t.book_ref
JOIN ticket_flights tf ON t.ticket_no = tf.ticket_no
JOIN flights f ON tf.flight_id = f.flight_id
JOIN aircrafts a ON f.aircraft_code = a.aircraft_code
WHERE a.model LIKE '%Airbus%'
ORDER BY b.book_ref ASC;


-- Q4: Your task is to identify the 'blockbuster territory'-the territory with the highest sales
-- volume-for each subcategory...
WITH subcategory_territory_sales AS (
    SELECT
        sub.subcategory_id,
        sub.subcategoryname,
        s.territory_id,
        SUM(s.orderquantity) AS total_sales_volume
    FROM
        sales s
    JOIN
        products p ON s.product_id = p.product_id
    JOIN
        subcategories sub ON p.subcategory_id = sub.subcategory_id
    GROUP BY
        sub.subcategory_id,
        sub.subcategoryname,
        s.territory_id
),
ranked_territories AS (
    SELECT
        subcategory_id,
        subcategoryname,
        territory_id,
        ROW_NUMBER() OVER (
            PARTITION BY subcategory_id
            ORDER BY total_sales_volume DESC, territory_id ASC
        ) AS rn
    FROM
        subcategory_territory_sales
)
SELECT
    subcategory_id,
    subcategoryname,
    territory_id
FROM
    ranked_territories
WHERE
    rn = 1
ORDER BY
    subcategory_id ASC;


-- Q5: The organization intends to offer a special coupon for every customer's third purchase...
WITH ranked_orders AS (
    SELECT
        customer_id,
        ordernumber,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id 
            ORDER BY MIN(orderdate), ordernumber
        ) AS rn
    FROM
        sales
    GROUP BY
        customer_id,
        ordernumber
)
SELECT
    c.customer_id,
    c.firstname || ' ' || c.lastname AS full_name,
    r.ordernumber AS third_order_id
FROM
    customers c
JOIN
    ranked_orders r ON c.customer_id = r.customer_id::text
WHERE
    r.rn = 3
ORDER BY
    c.customer_id ASC;
